/**
 * Sasta Dawa Finder - DRAP & Public Drug Data Ingestion & Sync Utility
 * Validates dataset integrity, checks duplicate IDs, ensures consistent salt_group_ids,
 * normalizes pricing, and compiles the offline embed bundle js/medicines_data_embed.js.
 */

const fs = require('fs');
const path = require('path');

const DATA_FILE = path.join(__dirname, '../data/medicines.json');
const EMBED_FILE = path.join(__dirname, '../js/medicines_data_embed.js');

function normalizeSlug(str) {
  return (str || '')
    .toString()
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, '')
    .replace(/\s+/g, '-');
}

function validateAndSync(inputData = null) {
  const rawData = inputData || JSON.parse(fs.readFileSync(DATA_FILE, 'utf8'));

  if (!Array.isArray(rawData)) {
    throw new Error('Dataset must be a JSON array.');
  }

  const seenIds = new Set();
  const saltGroups = new Map();
  const categories = new Set();
  const cleanedList = [];

  for (let i = 0; i < rawData.length; i++) {
    const item = rawData[i];

    // Ensure ID
    if (!item.id) {
      item.id = `${normalizeSlug(item.brand_name)}-${normalizeSlug(item.strength)}-${normalizeSlug(item.dosage_form)}`;
    }

    if (seenIds.has(item.id)) {
      throw new Error(`Duplicate medicine ID found: "${item.id}" at index ${i}`);
    }
    seenIds.add(item.id);

    // Validate essential fields
    if (!item.brand_name || !item.generic_name || !item.strength || !item.dosage_form) {
      throw new Error(`Missing required textual fields in item: ${JSON.stringify(item)}`);
    }

    if (typeof item.pack_price_pkr !== 'number' || item.pack_price_pkr <= 0) {
      throw new Error(`Invalid pack_price_pkr for ${item.id}: ${item.pack_price_pkr}`);
    }

    if (typeof item.pack_size !== 'number' || item.pack_size <= 0) {
      throw new Error(`Invalid pack_size for ${item.id}: ${item.pack_size}`);
    }

    // Ensure unit price calculation
    const calculatedUnitPrice = parseFloat((item.pack_price_pkr / item.pack_size).toFixed(2));
    if (!item.unit_price_pkr || Math.abs(item.unit_price_pkr - calculatedUnitPrice) > 0.05) {
      item.unit_price_pkr = calculatedUnitPrice;
    }

    // Default metadata fields
    if (typeof item.price_is_estimate !== 'boolean') {
      item.price_is_estimate = false;
    }
    if (typeof item.verified !== 'boolean') {
      item.verified = true;
    }
    if (typeof item.popular !== 'boolean') {
      item.popular = false;
    }
    if (!Array.isArray(item.synonyms)) {
      item.synonyms = [];
    }
    if (!item.confidence) {
      item.confidence = item.verified ? 'high' : 'unverified';
    }

    // Track statistics
    categories.add(item.category || 'General');
    if (!saltGroups.has(item.salt_group_id)) {
      saltGroups.set(item.salt_group_id, []);
    }
    saltGroups.get(item.salt_group_id).push(item.id);

    cleanedList.push(item);
  }

  // Write normalized JSON to data/medicines.json
  fs.writeFileSync(DATA_FILE, JSON.stringify(cleanedList, null, 2) + '\n', 'utf8');

  // Write embedded script to js/medicines_data_embed.js
  const embedHeader = `/**\n * Embedded Medicines Dataset Bundle\n * Auto-generated by scripts/sync_drug_data.js on ${new Date().toISOString()}\n * Enables 100% offline, zero-CORS operation for file:// protocol.\n */\n\n`;
  const embedCode = `${embedHeader}(function () {\n  'use strict';\n  const dataset = ${JSON.stringify(cleanedList, null, 2)};\n  window.__EMBEDDED_MEDICINES__ = dataset;\n  window.__EMBEDDED_MEDICINES_DATA__ = dataset;\n})();\n`;
  fs.writeFileSync(EMBED_FILE, embedCode, 'utf8');

  let singleSourceCount = 0;
  let multiSourceCount = 0;
  for (const [, group] of saltGroups) {
    if (group.length > 1) {
      multiSourceCount += group.length;
    } else {
      singleSourceCount += 1;
    }
  }

  return {
    totalMedicines: cleanedList.length,
    totalCategories: categories.size,
    totalSaltGroups: saltGroups.size,
    multiSourceAlternativesCount: multiSourceCount,
    singleSourceCount: singleSourceCount,
    status: 'SUCCESS'
  };
}

if (require.main === module) {
  try {
    console.log('🔄 Sasta Dawa Finder: Validating & Synchronizing Drug Database...');
    const result = validateAndSync();
    console.log('✅ Synchronization Complete:');
    console.log(`   - Total Medicines: ${result.totalMedicines}`);
    console.log(`   - Therapeutic Salt Groups: ${result.totalSaltGroups}`);
    console.log(`   - Therapeutic Categories: ${result.totalCategories}`);
    console.log(`   - Medicines with generic alternatives: ${result.multiSourceAlternativesCount}`);
    console.log(`   - Proprietary / Single-source medicines: ${result.singleSourceCount}`);
    console.log(`   - Embed bundle generated: js/medicines_data_embed.js`);
  } catch (err) {
    console.error('❌ Data synchronization error:', err.message);
    process.exit(1);
  }
}

module.exports = {
  validateAndSync,
  normalizeSlug
};
